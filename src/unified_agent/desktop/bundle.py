@dataclass
class BundleResult:
    path: Path
    mode: str  # "launcher" | "frozen"
    python: str
    has_icon: bool
    notes: list[str]

    def summary(self) -> str:
        lines = [
            f"bundle:  {self.path}",
            f"mode:    {self.mode}",
            f"python:  {self.python}",
            f"icon:    {'yes' if self.has_icon else 'no (iconutil unavailable)'}",
        ]
        lines += [f"note:    {note}" for note in self.notes]
        return "\n".join(lines)


def build_app_bundle(
    *,
    target_dir: Path,
    version: str,
    name: str = APP_NAME,
    python: str | None = None,
    frozen: bool = False,
    console_script: str = "uaa",
) -> BundleResult:
    """Create `<name>.app` under `target_dir`."""
    if frozen:
        # Checked before the platform gate: "PyInstaller is not wired up" is
        # true on every platform, and reporting the platform first would send
        # a Linux user chasing the wrong problem.
        raise BundleError(
            "frozen bundles need PyInstaller, which is not wired up here. "
            "Install it and build with:\n"
            "  pip install pyinstaller\n"
            "  pyinstaller --windowed --name "
            f"{name} --collect-all webview "
            f"--osx-bundle-identifier {BUNDLE_ID} "
            "$(python -c 'import unified_agent,os;print(os.path.dirname("
            "unified_agent.__file__))')/desktop/__main__.py"
        )
    if sys.platform != "darwin":
        raise BundleError(
            f".app bundles are macOS-only; this is {sys.platform}. "
            "On Linux/Windows use `uaa desktop` to open the window directly."
        )

    interpreter = python or sys.executable
    final = target_dir / f"{name}.app"
    target_dir.mkdir(parents=True, exist_ok=True)

    # Build into a staging directory and swap it in with a rename. Two wins:
    # a failure halfway through never leaves a half-written app where the user
    # can double-click it, and the replacement of an existing bundle is a
    # rename rather than a recursive delete -- which some environments refuse
    # outright, and which is the kind of thing that only breaks on the second
    # build.
    staging = Path(tempfile.mkdtemp(dir=target_dir, prefix=f".{name}.building-"))
    contents = staging / "Contents"
    macos = contents / "MacOS"
    resources = contents / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    executable = name
    launcher = macos / executable
    launcher.write_text(LAUNCHER_SCRIPT.format(python=interpreter), encoding="utf-8")
    launcher.chmod(0o755)

    (contents / "Info.plist").write_text(
        INFO_PLIST.format(
            name=name,
            display="unified-ai-agent",
            bundle_id=BUNDLE_ID,
            executable=executable,
            version=version,
            copyright=f"MIT licensed. Built by {console_script} desktop --bundle.",
        ),
        encoding="utf-8",
    )

    icon_result = build_icns(resources)

    replaced: Path | None = None
    if final.exists():
        replaced = target_dir / f".{name}.replaced-{int(time.time())}"
        os.rename(final, replaced)
    os.rename(staging, final)

    notes = [
        "launcher bundle: it runs the installed package with the interpreter "
        "above. Moving or deleting that environment breaks the app.",
        "the app writes to ~/Library/Logs/unified-ai-agent.log",
    ]
    if replaced is not None:
        try:
            shutil.rmtree(replaced)
        except (Exception, SystemExit):
            # Best-effort. A refusal here must not fail the build, but it also
            # must not be silent -- the user has a leftover directory to
            # clean up and deserves to know where it is.
            notes.append(f"could not remove the previous bundle; it is at {replaced}")
    if not icon_result:
        notes.append(f"no app icon: {icon_result.reason}")
    else:
        notes.append("icon generated procedurally (stdlib PNG + iconutil), no assets vendored")

    return BundleResult(
        path=final,
        mode="launcher",
        python=interpreter,
        has_icon=bool(icon_result),
        notes=notes,
    )


